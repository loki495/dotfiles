#!/usr/bin/env python3
"""Export the Dibs `rule` records to files the rule-inject hook and other agents read.

Public rules go to ai/rules.md, rules labelled `private` to ~/.dotfiles-private/ai/rules.private.md.
Each rule is a `## <id>@<revision> <title>` heading followed by its text (the record body up to
the first Trigger:/Check:/Applies to:/Source:/Merged candidates:/Always:/Keys:/Pull when: line).
Each rule has one label `tier always|trigger|pull`: the always lines and the rule index are written
between the rules-export markers of RULES.md (public) and CLAUDE.private.md (private), and the
key -> rule ids map to the triggers JSON files. A file is rewritten only when its content changed.
--commit commits just those paths in their own repo (never pushes) and skips a RULES.md or private
markdown file that already has uncommitted changes. --check writes nothing and reports drift.

Usage: rules-export.py [--public PATH] [--private PATH] [--rules-md PATH] [--private-md PATH]
                       [--triggers PATH] [--private-triggers PATH] [--commit | --check]
Exit: 0 ok, 1 --check found drift, 2 Dibs unreachable (nothing written), 3 validation or marker
problems (rules.md is still exported; each problem goes to stderr).
"""
import json
import argparse
import importlib.machinery
import importlib.util
import os
import re
import subprocess
import sys

_here = os.path.dirname(os.path.abspath(__file__))
_loader = importlib.machinery.SourceFileLoader("dibs_measure", os.path.join(_here, "dibs-measure.py"))
M = importlib.util.module_from_spec(importlib.util.spec_from_loader("dibs_measure", _loader))
_loader.exec_module(M)

PUBLIC = os.path.join(os.path.dirname(_here), "rules.md")
PRIVATE = os.path.expanduser("~/.dotfiles-private/ai/rules.private.md")
RULES_MD = os.path.join(os.path.dirname(_here), "RULES.md")
PRIVATE_MD = os.path.expanduser("~/.dotfiles-private/ai/CLAUDE.private.md")
TRIGGERS = os.path.join(os.path.dirname(_here), "rules-triggers.json")
PRIVATE_TRIGGERS = os.path.expanduser("~/.dotfiles-private/ai/rules-triggers.private.json")
META = re.compile(r"^(Trigger|Check|Applies to|Source|Merged candidates|Always|Keys|Pull when):", re.M)
START, END = "<!-- rules-export:start -->", "<!-- rules-export:end -->"
TIERS = ("always", "trigger", "pull")
KEYS = frozenset("""git-commit git-push git-history git-add-all test-run test-file php-tool live-check live-repo
db-cli quota-check agent-launch session-launch peer-send peer-prompt dibs-create dibs-revise dibs-comment
dibs-claim dibs-complete dibs-release screenshot schedule md-edit project-doc todo-note home-net
work-creds""".split())
PULL_LINE = ("Pull: when an index line below applies and its text isn't in your context, run "
             "`awk '/^## /{p=($2 ~ /^<id>@/)} p' ~/dotfiles/ai/rules.md`, or `todo_show <id>` with `fullBody`.")
HEADER = ("<!-- Generated by ai/scripts/rules-export.py from the Dibs rule records; edits are overwritten. -->\n"
          "<!-- {what} -->\n")


def rule_text(body):
    m = META.search(body or "")
    return (body[:m.start()] if m else body or "").strip()


def render(rules, what):
    """A title is one line and a text line never starts with `## `, so a record cannot forge another rule's heading."""
    out = [HEADER.format(what=what)]
    for r in sorted(rules, key=lambda r: r["id"]):
        title = " ".join(str(r["title"]).split())
        text = re.sub(r"^(\s*)##", r"\1 ##", r["text"], flags=re.M)
        out.append(f"\n## {r['id']}@{r['revision']} {title}\n{text}\n")
    return "".join(out)


def meta_line(body, name):
    m = re.search(rf"^{name}:[ \t]*(.*?)[ \t]*$", body or "", re.M)
    return m.group(1) if m else ""


def gather():
    """[{id, revision, title, text, private, tiers, keys, always, pull}] for every open rule record; raises if Dibs is unreachable."""
    out = []
    for t in M.dibs_json("todo:agent:list")["tasks"]:
        if "rule" in t.get("labels", []) and t.get("state") == "OPEN":
            d = M.dibs_json("todo:agent:show", str(t["id"]))
            labels, body = d.get("labels", []), d.get("body")
            out.append({"id": d["id"], "revision": d["revision"], "title": d["title"],
                        "text": rule_text(body), "private": "private" in labels,
                        "tiers": [l[5:] for l in labels if l.startswith("tier ")],
                        "keys": [k for k in re.split(r"[,\s]+", meta_line(body, "Keys")) if k],
                        "always": meta_line(body, "Always"), "pull": meta_line(body, "Pull when")})
    return out


def validate(rules):
    """{id: [error, ...]} for rules whose tier, keys or tier text are wrong; {} when all are fine."""
    out = {}
    for r in rules:
        errs = []
        if len(r["tiers"]) != 1 or r["tiers"][0] not in TIERS:
            errs.append("needs exactly one tier label (tier always, tier trigger or tier pull)")
        tier = r["tiers"][0] if len(r["tiers"]) == 1 else None
        if tier == "always" and not r["always"]:
            errs.append("tier always needs an Always: line")
        if tier == "trigger" and not r["keys"]:
            errs.append("tier trigger needs a known key")
        if tier == "pull" and not r["pull"]:
            errs.append("tier pull needs a Pull when: line")
        errs += [f"unknown key {k}" for k in r["keys"] if k not in KEYS]
        if errs:
            out[r["id"]] = errs
    return out


def render_always(rules):
    return "\n".join(f"- {r['always']}" for r in sorted(rules, key=lambda r: r["id"]) if "always" in r["tiers"])


def render_index(rules):
    lines = []
    for r in sorted(rules, key=lambda r: r["id"]):
        title = " ".join(str(r["title"]).split()).removeprefix("Rule: ")
        if "trigger" in r["tiers"]:
            lines.append(f"- {r['id']} [{', '.join(r['keys'])}] {title}")
        elif "pull" in r["tiers"]:
            lines.append(f"- {r['id']} [pull: {r['pull']}] {title}")
    return "\n".join(lines)


def render_block(rules):
    return (f"### Always-on rules\n{render_always(rules)}\n\n### Rule index\n{PULL_LINE}\n"
            f"{render_index(rules)}\n")


def render_triggers(rules):
    keyed = {}
    for r in rules:
        for k in r["keys"]:
            keyed.setdefault(k, []).append(r["id"])
    return json.dumps({k: sorted(v) for k, v in keyed.items()}, indent=1, sort_keys=True) + "\n"


def replace_block(text, block):
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise ValueError(f"needs exactly one {START} followed by one {END}")
    return text[:text.index(START) + len(START)] + "\n" + block.rstrip("\n") + "\n" + text[text.index(END):]


def read(path):
    try:
        with open(path) as f:
            return f.read()
    except OSError:
        return None


def write_if_changed(path, content):
    if read(path) == content:
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
    return True


def is_dirty(path):
    st = subprocess.run(["git", "-C", os.path.dirname(path), "status", "--porcelain", "--", path],
                        capture_output=True, text=True)
    return st.returncode == 0 and bool(st.stdout.strip())


def commit(path):
    d = os.path.dirname(path)
    git = ["git", "-C", d]
    top = subprocess.run([*git, "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if top.returncode != 0:
        return
    subprocess.run([*git, "add", "--", path], check=True, capture_output=True)
    subprocess.run([*git, "commit", "-m", "Rules export: refresh from the rule records", "--", path],
                   check=True, capture_output=True)


def split(rules):
    return [r for r in rules if not r["private"]], [r for r in rules if r["private"]]


def tier_outputs(rules, rules_md, private_md, triggers, private_triggers, problems):
    """{path: content} for the given tier files; {} (and problems filled) if any rule or marker is bad."""
    errors = validate(rules)
    problems.extend(f"{i}: {e}" for i, errs in sorted(errors.items()) for e in errs)
    if errors:
        return {}
    pub, priv = split(rules)
    out = {}
    for path, group in ((rules_md, pub), (private_md, priv)):
        if path:
            try:
                out[path] = replace_block(read(path) or "", render_block(group))
            except ValueError as e:
                problems.append(f"{path}: {e}")
                return {}
    for path, group in ((triggers, pub), (private_triggers, priv)):
        if path:
            out[path] = render_triggers(group)
    return out


def generated(rules, public, private):
    pub, priv = split(rules)
    return {public: render(pub, "Public rules."),
            private: render(priv, "Private rules; never copy into a public repo.")}


def export(public=PUBLIC, private=PRIVATE, do_commit=False, rules=None, rules_md=None, private_md=None,
           triggers=None, private_triggers=None, problems=None):
    """Write the files; returns the paths that changed. The tier files are skipped on any problem."""
    rules = gather() if rules is None else rules
    problems = [] if problems is None else problems
    changed = []
    outputs = generated(rules, public, private)
    if any((rules_md, private_md, triggers, private_triggers)):
        outputs.update(tier_outputs(rules, rules_md, private_md, triggers, private_triggers, problems))
    for path, content in outputs.items():
        if path in (rules_md, private_md) and do_commit and read(path) != content and is_dirty(path):
            continue
        if write_if_changed(path, content):
            changed.append(path)
            if do_commit:
                commit(path)
    return changed


def check(public, private, rules_md, private_md, triggers, private_triggers, rules=None, problems=None):
    """Paths whose content differs from what an export would write; writes nothing."""
    rules = gather() if rules is None else rules
    outputs = generated(rules, public, private)
    outputs.update(tier_outputs(rules, rules_md, private_md, triggers, private_triggers,
                                [] if problems is None else problems))
    return [path for path, content in outputs.items() if read(path) != content]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--public", default=PUBLIC)
    ap.add_argument("--private", default=PRIVATE)
    ap.add_argument("--rules-md", default=RULES_MD)
    ap.add_argument("--private-md", default=PRIVATE_MD)
    ap.add_argument("--triggers", default=TRIGGERS)
    ap.add_argument("--private-triggers", default=PRIVATE_TRIGGERS)
    ap.add_argument("--commit", action="store_true", help="commit changed files in their repo (never pushes)")
    ap.add_argument("--check", action="store_true", help="report drift (exit 1), write nothing")
    a = ap.parse_args()
    tier_files = (a.rules_md, a.private_md, a.triggers, a.private_triggers)
    problems, drift = [], []
    try:
        if a.check:
            drift = check(a.public, a.private, *tier_files, problems=problems)
            for p in drift:
                print(f"drift {p}")
        else:
            for p in export(a.public, a.private, a.commit, rules_md=a.rules_md, private_md=a.private_md,
                            triggers=a.triggers, private_triggers=a.private_triggers, problems=problems):
                print(f"updated {p}")
    except (RuntimeError, ValueError, OSError, KeyError, subprocess.CalledProcessError) as e:
        print(f"Dibs unreachable or unreadable, nothing written: {e}", file=sys.stderr)
        return 2
    for p in problems:
        print(p, file=sys.stderr)
    return 3 if problems else 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
