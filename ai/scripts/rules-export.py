#!/usr/bin/env python3
"""Export the Dibs `rule` records to files the rule-inject hook and other agents read.

Public rules go to ai/rules.md, rules labelled `private` to ~/.dotfiles-private/ai/rules.private.md.
Each rule is a `## <id>@<revision> <title>` heading followed by its text (the record body up to
the first Trigger:/Check:/Applies to:/Source:/Merged candidates: line). A file is rewritten only
when its content changed. --commit commits just those paths in their own repo; it never pushes.

Usage: rules-export.py [--public PATH] [--private PATH] [--commit]
Exit: 0 ok, 2 Dibs unreachable (nothing written).
"""
import argparse
import importlib.machinery
import importlib.util
import os
import re
import subprocess
import sys

_here = os.path.dirname(os.path.abspath(__file__))
_loader = importlib.machinery.SourceFileLoader("dibs_measure", os.path.join(_here, "dibs-measure.py"))
M = importlib.util.module_from_spec(importlib.util.spec_from_loader("dibs_measure", _loader))
_loader.exec_module(M)

PUBLIC = os.path.join(os.path.dirname(_here), "rules.md")
PRIVATE = os.path.expanduser("~/.dotfiles-private/ai/rules.private.md")
META = re.compile(r"^(Trigger|Check|Applies to|Source|Merged candidates):", re.M)
HEADER = ("<!-- Generated by ai/scripts/rules-export.py from the Dibs rule records; edits are overwritten. -->\n"
          "<!-- {what} -->\n")


def rule_text(body):
    m = META.search(body or "")
    return (body[:m.start()] if m else body or "").strip()


def render(rules, what):
    """A title is one line and a text line never starts with `## `, so a record cannot forge another rule's heading."""
    out = [HEADER.format(what=what)]
    for r in sorted(rules, key=lambda r: r["id"]):
        title = " ".join(str(r["title"]).split())
        text = re.sub(r"^(\s*)##", r"\1 ##", r["text"], flags=re.M)
        out.append(f"\n## {r['id']}@{r['revision']} {title}\n{text}\n")
    return "".join(out)


def gather():
    """[{id, revision, title, text, private}] for every open rule record; raises if Dibs is unreachable."""
    out = []
    for t in M.dibs_json("todo:agent:list")["tasks"]:
        if "rule" in t.get("labels", []) and t.get("state") == "OPEN":
            d = M.dibs_json("todo:agent:show", str(t["id"]))
            out.append({"id": d["id"], "revision": d["revision"], "title": d["title"],
                        "text": rule_text(d.get("body")), "private": "private" in d.get("labels", [])})
    return out


def write_if_changed(path, content):
    try:
        with open(path) as f:
            if f.read() == content:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
    return True


def commit(path):
    d = os.path.dirname(path)
    git = ["git", "-C", d]
    top = subprocess.run([*git, "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if top.returncode != 0:
        return
    subprocess.run([*git, "add", "--", path], check=True, capture_output=True)
    subprocess.run([*git, "commit", "-m", "Rules export: refresh from the rule records", "--", path],
                   check=True, capture_output=True)


def export(public=PUBLIC, private=PRIVATE, do_commit=False, rules=None):
    """Write both files; returns the paths that changed."""
    rules = gather() if rules is None else rules
    changed = []
    for path, group, what in ((public, [r for r in rules if not r["private"]], "Public rules."),
                              (private, [r for r in rules if r["private"]], "Private rules; never copy into a public repo.")):
        if write_if_changed(path, render(group, what)):
            changed.append(path)
            if do_commit:
                commit(path)
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--public", default=PUBLIC)
    ap.add_argument("--private", default=PRIVATE)
    ap.add_argument("--commit", action="store_true", help="commit changed files in their repo (never pushes)")
    a = ap.parse_args()
    try:
        for p in export(a.public, a.private, a.commit):
            print(f"updated {p}")
    except (RuntimeError, ValueError, OSError, KeyError, subprocess.CalledProcessError) as e:
        print(f"Dibs unreachable or unreadable, nothing written: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
